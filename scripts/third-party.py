#!/usr/bin/env python3
"""Writes THIRD-PARTY.md: the licence of every library linked into the Tracyo executable.

Usage: python3 scripts/third-party.py [--check]

Takes the normal (not dev, not build) dependencies of `tracyo-app` from `cargo metadata` for each
platform of deny.toml, the union of the five, and prints each crate with its licence expression and
the licence files of its package, texts shared by several crates once. The bundled assets (font,
icons, OCR model) are added from `assets/`. `--check` fails when the file on disk is out of date.
Needs the crates in the cargo registry (run `cargo fetch` first); never touches the network itself.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY.md"
TARGETS = [
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
    "x86_64-pc-windows-msvc",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
]
LICENCE_FILE_STARTS = ("license", "licence", "copying", "notice", "unlicense", "copyright")
ASSETS = [
    ("Liberation Sans (user interface font)", "SIL OFL 1.1", "assets/fonts/OFL.txt"),
    ("lucide icons", "ISC", "assets/icons/lucide/LICENSE"),
    (
        "PaddleOCR Latin text recognition model",
        "Apache-2.0",
        "assets/models/paddleocr-latin/LICENSE",
    ),
]


def cargo(*args):
    return subprocess.run(
        ["cargo", *args, "--locked", "--offline"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def linked(target):
    """(name, version) of every crate `cargo tree` finds under tracyo-app for `target`, normal
    dependencies only (not dev, not build): what the real feature resolution links there."""
    out = cargo("tree", "-p", "tracyo-app", "--target", target, "-e", "normal", "--prefix", "none", "--format", "{p}")
    found = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("v"):
            found.add((parts[0], parts[1][1:]))
    return found


def collect():
    """The metadata of the crates linked on at least one target, by (name, version)."""
    wanted = set()
    for target in TARGETS:
        wanted |= linked(target)
    meta = json.loads(cargo("metadata", "--format-version", "1"))
    by_key = {(p["name"], p["version"]): p for p in meta["packages"]}
    return {k: by_key[k] for k in sorted(wanted) if not k[0].startswith("tracyo-")}


def licence_files(package):
    folder = pathlib.Path(package["manifest_path"]).parent
    found = []
    for path in sorted(folder.iterdir()):
        if path.is_file() and path.name.lower().startswith(LICENCE_FILE_STARTS):
            found.append(path)
    return found


def fence(text):
    return "```text\n" + text.strip("\n") + "\n```\n"


def render():
    crates = collect()
    texts = {}
    rows, missing = [], []
    for (name, version), p in sorted(crates.items()):
        expr = p.get("license") or p.get("license_file") or "see repository"
        files = licence_files(p)
        keys = []
        for f in files:
            body = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
            key = hashlib.sha256(body.encode()).hexdigest()[:12]
            texts.setdefault(key, [body, set()])[1].add(f"{name} {version}")
            keys.append(key)
        if not files:
            missing.append((name, version, expr, p.get("repository") or ""))
        rows.append((name, version, expr, p.get("repository") or "", keys))
    lines = [
        "# Third-party licences",
        "",
        "Tracyo is AGPL-3.0-or-later (`LICENSE`). The executable links the libraries below and embeds",
        "the assets after them. This file is generated by `scripts/third-party.py` from `Cargo.lock`;",
        "do not edit it by hand.",
        "",
        "## Libraries",
        "",
        "| Crate | Version | Licence | Text |",
        "|---|---|---|---|",
    ]
    for name, version, expr, repo, keys in rows:
        refs = ", ".join(f"[{k}](#text-{k})" for k in sorted(set(keys))) or "none in the package"
        lines.append(f"| {name} | {version} | {expr} | {refs} |")
    if missing:
        lines += ["", "Crates whose package carries no licence file; the expression above is their licence and the", "copyright notice is in the repository named here:", ""]
        for name, version, expr, repo in missing:
            lines.append(f"- {name} {version}, {expr}, {repo or 'no repository given'}")
    lines += ["", "## Bundled assets", ""]
    for what, licence, path in ASSETS:
        body = (ROOT / path).read_text(encoding="utf-8").replace("\r\n", "\n")
        lines += [f"### {what}: {licence}", "", f"From `{path}`.", "", fence(body)]
    lines += ["## Licence texts of the libraries", ""]
    for key, (body, who) in sorted(texts.items(), key=lambda kv: sorted(kv[1][1])[0]):
        names = sorted(who)
        shown = ", ".join(names[:8]) + (f" and {len(names) - 8} more" if len(names) > 8 else "")
        lines += [f'<a id="text-{key}"></a>', f"### Text {key}", "", f"Shipped by: {shown}.", "", fence(body)]
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("THIRD-PARTY.md is out of date: run python3 scripts/third-party.py")
        print("THIRD-PARTY.md is up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
